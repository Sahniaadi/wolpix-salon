export function initJournalReader() {
  const modalBackdrop = document.getElementById('journalModal');
  const modalClose = document.getElementById('journalModalClose');
  const titleEl = document.getElementById('journalModalTitle');
  const metaEl = document.getElementById('journalModalMeta');
  const bodyEl = document.getElementById('journalModalBody');
  const readCards = document.querySelectorAll('.journal-card');

  if (!modalBackdrop || !titleEl || !bodyEl) return;

  function openArticle(key) {
    const art = JOURNAL_ARTICLES[key];
    if (!art) return;

    titleEl.textContent = art.title;
    metaEl.innerHTML = `
      <span style="font-weight: 700; color: var(--electric-blue);">${art.category}</span> &bull; 
      <span>${art.author}</span> &bull; 
      <span>${art.readTime}</span>
    `;
    bodyEl.innerHTML = art.content;

    modalBackdrop.classList.add('active');
    document.body.style.overflow = 'hidden';
  }

  function closeArticle() {
    modalBackdrop.classList.remove('active');
    document.body.style.overflow = '';
  }

  readCards.forEach(card => {
    card.addEventListener('click', () => {
      const key = card.dataset.articleKey;
      openArticle(key);
    });
  });

  if (modalClose) modalClose.addEventListener('click', closeArticle);
  modalBackdrop.addEventListener('click', (e) => {
    if (e.target === modalBackdrop) closeArticle();
  });
}
